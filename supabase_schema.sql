-- Guardado atómico: si falla una operación, se revierte todo el lote.
create or replace function public.aplicar_lote_atomico(
  p_carga_id bigint,
  p_productos jsonb
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if p_carga_id is null
     or p_productos is null
     or jsonb_typeof(p_productos) <> 'array' then
    raise exception 'Datos del lote inválidos';
  end if;

  insert into movimientos_inventario (
    carga_id, clave, producto, categoria, medida, variante,
    cantidad_agregada, unidad, observaciones, ubicacion
  )
  select
    p_carga_id,
    x.clave,
    coalesce(x.producto, ''),
    coalesce(x.categoria, 'Otros'),
    coalesce(x.medida, ''),
    coalesce(x.variante, ''),
    x.cantidad,
    coalesce(x.unidad, ''),
    coalesce(x.observaciones, ''),
    coalesce(x.ubicacion, 'Pasillo')
  from jsonb_to_recordset(p_productos) as x(
    clave text,
    producto text,
    categoria text,
    medida text,
    variante text,
    cantidad numeric,
    unidad text,
    observaciones text,
    ubicacion text
  );

  insert into inventario (
    clave, producto, categoria, medida, variante,
    cantidad, unidad, observaciones, ubicacion
  )
  select
    x.clave,
    max(coalesce(x.producto, '')),
    max(coalesce(x.categoria, 'Otros')),
    max(coalesce(x.medida, '')),
    max(coalesce(x.variante, '')),
    sum(x.cantidad),
    max(coalesce(x.unidad, '')),
    max(coalesce(x.observaciones, '')),
    max(coalesce(x.ubicacion, 'Pasillo'))
  from jsonb_to_recordset(p_productos) as x(
    clave text,
    producto text,
    categoria text,
    medida text,
    variante text,
    cantidad numeric,
    unidad text,
    observaciones text
  )
  group by x.clave
  on conflict (clave) do update
  set cantidad = inventario.cantidad + excluded.cantidad,
      ubicacion = excluded.ubicacion,
      actualizado_en = now();
end;
$$;

revoke all on function public.aplicar_lote_atomico(bigint, jsonb)
from public;

grant execute on function public.aplicar_lote_atomico(bigint, jsonb)
to service_role;
