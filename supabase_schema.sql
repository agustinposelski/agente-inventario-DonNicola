create table if not exists public.inventario (
  id bigint generated by default as identity primary key,
  clave text not null unique,
  producto text not null,
  categoria text not null default 'Otros',
  medida text not null default '',
  variante text not null default '',
  cantidad numeric not null check (cantidad >= 0),
  unidad text not null default '',
  observaciones text not null default '',
  ubicacion text not null default 'Pasillo' check (ubicacion in ('Pasillo', 'Galpón', 'Nonna')),
  precio_min numeric,
  precio_referencia numeric,
  precio_max numeric,
  moneda text not null default 'ARS',
  fuentes_precio jsonb not null default '[]'::jsonb,
  precio_confianza text,
  precio_actualizado_en timestamptz,
  actualizado_en timestamptz not null default now()
);

